// Generates docs/api/endpoints.md from the NestJS controllers' route metadata (apps/api/src/modules/*/*.controller.ts).
// Run with tsx: `node --import tsx scripts/gen-endpoints.mjs [--check]`; --check fails if the committed file is stale.
import "reflect-metadata";
import { readFile, writeFile } from "node:fs/promises";
import { RequestMethod } from "@nestjs/common";
import { PATH_METADATA, METHOD_METADATA } from "@nestjs/common/constants.js";

import { MODULE_METADATA } from "@nestjs/common/constants.js";

const { FEATURE_MODULES } = await import("../apps/api/src/server.ts");
const { ROUTE_META } = await import("../apps/api/src/http/route-kit.ts");
const CONTROLLERS = FEATURE_MODULES.flatMap((m) => Reflect.getMetadata(MODULE_METADATA.CONTROLLERS, m) ?? []);

const rows = [];
for (const ctrl of CONTROLLERS) {
  const base = Reflect.getMetadata(PATH_METADATA, ctrl);
  for (const name of Object.getOwnPropertyNames(ctrl.prototype)) {
    const h = ctrl.prototype[name];
    if (name === "constructor" || typeof h !== "function" || Reflect.getMetadata(PATH_METADATA, h) === undefined) continue;
    if (Reflect.getMetadata(ROUTE_META.binary, h)) continue;
    const meta = (k) => Reflect.getMetadata(k, h) === true;
    rows.push({ method: RequestMethod[Reflect.getMetadata(METHOD_METADATA, h)], path: `/${base}/${Reflect.getMetadata(PATH_METADATA, h)}`, public: meta(ROUTE_META.public), idem: meta(ROUTE_META.idempotent) });
  }
}
const access = (r) => (r.public ? "Public" : r.path.startsWith("/v1/ops") ? "Operator + step-up" : "Session");
const lines = [
  "# Implemented HTTP endpoints", "",
  "Generated by `npm run docs:endpoints` from the NestJS feature controllers in `apps/api/src/modules` (all under `/v1`). Conventions are in [conventions.md](./conventions.md); resource shapes in [resources.md](./resources.md).", "",
  "Legend: **Public** needs no session. **Session** uses `Authorization: Bearer <token>` (the web tier attaches it from an HttpOnly cookie). **Operator + step-up** additionally needs an operator capability and a recent OTP step-up. **Idem** requires an `Idempotency-Key` header.", "",
  "| Method | Path | Access | Idem |", "|---|---|---|---|",
  ...rows.map((r) => `| ${r.method} | \`${r.path.replace(/\/{2,}/g, "/")}\` | ${access(r)} | ${r.idem ? "yes" : ""} |`),
  "",
  "There are no internal endpoints: the worker runs the same services directly against the database.", "",
  "Binary endpoints handled outside the JSON pipeline: `PUT /v1/uploads/:mediaId?exp=&sig=` (signed direct upload, no session) and `GET /v1/media/:mediaId` (authorised download of approved media). Also `GET /healthz` and `GET /readyz` (unversioned).", "",
  "Errors use the problem format from the conventions document with `code`, `messageKey` and a localized `message` (`?lang=ta|en` or `Accept-Language`).", "",
];
const out = lines.join("\n");
if (process.argv.includes("--check")) {
  const cur = await readFile("docs/api/endpoints.md", "utf8").catch(() => "");
  if (cur !== out) { console.error("docs/api/endpoints.md is stale; run npm run docs:endpoints"); process.exit(1); }
  console.log(`endpoints doc is current (${rows.length} routes)`);
} else {
  await writeFile("docs/api/endpoints.md", out);
  console.log(`wrote ${rows.length} routes`);
}
