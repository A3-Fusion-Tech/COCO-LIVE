// Generates docs/api/endpoints.md from the route table in apps/api/src/server.ts.
// `node scripts/gen-endpoints.mjs --check` fails if the committed file is stale.
import { readFile, writeFile } from "node:fs/promises";

const src = await readFile("apps/api/src/server.ts", "utf8");
const rows = [...src.matchAll(/route\("(\w+)", "([^"]+)", \{([^}]*)\}/g)];
const access = (path, opts) => (opts.includes("internal: true") ? "Service token" : opts.includes("auth: false") ? "Public" : path.startsWith("/ops") ? "Operator + step-up" : "Session");
const lines = [
  "# Implemented HTTP endpoints", "",
  "Generated by `npm run docs:endpoints` from `apps/api/src/server.ts` (all under `/v1`). Conventions are in [conventions.md](./conventions.md); resource shapes in [resources.md](./resources.md).", "",
  "Legend: **Public** needs no session. **Session** uses `Authorization: Bearer <token>` (the web tier attaches it from an HttpOnly cookie). **Operator + step-up** additionally needs an operator capability and a recent OTP step-up. **Service token** is for the worker (`x-internal-token`). **Idem** requires an `Idempotency-Key` header.", "",
  "| Method | Path | Access | Idem |", "|---|---|---|---|",
  ...rows.map(([, m, p, o]) => `| ${m} | \`/v1${p}\` | ${access(p, o)} | ${o.includes("idem: true") ? "yes" : ""} |`),
  "",
  "Binary endpoints handled outside the JSON pipeline: `PUT /v1/uploads/:mediaId?exp=&sig=` (signed direct upload, no session) and `GET /v1/media/:mediaId` (authorised download of approved media). Also `GET /healthz` and `GET /readyz` (unversioned).", "",
  "Errors use the problem format from the conventions document with `code`, `messageKey` and a localized `message` (`?lang=ta|en` or `Accept-Language`).", "",
];
const out = lines.join("\n");
if (process.argv.includes("--check")) {
  const cur = await readFile("docs/api/endpoints.md", "utf8").catch(() => "");
  if (cur !== out) { console.error("docs/api/endpoints.md is stale; run npm run docs:endpoints"); process.exit(1); }
  console.log(`endpoints doc is current (${rows.length} routes)`);
} else {
  await writeFile("docs/api/endpoints.md", out);
  console.log(`wrote ${rows.length} routes`);
}
