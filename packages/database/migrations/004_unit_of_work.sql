-- Per-request units of work (ADR-010): many API/worker processes write concurrently, so
--  * every document table gets a stable insertion order (ord) and a GIN index for doc @> queries;
--  * append-only logs take their idx from a sequence instead of the single writer's array length;
--  * notification dedupe keys are unique so concurrent duplicates collapse into one.
