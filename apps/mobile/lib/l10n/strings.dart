/// Looks up UI text for one language, falling back to English and then to the key itself.
class S {
  const S(this.lang);

  final String lang;

  bool get isTamil => lang == 'ta';

  String t(String key) => _catalog[lang]?[key] ?? _catalog['en']![key] ?? key;

  /// Text for an enum-like code (status, stage, unit...) with the raw code as fallback.
  String code(String prefix, String? value) {
    if (value == null || value.isEmpty) return '—';
    final key = '$prefix.$value';
    final text = t(key);
    return text == key ? value : text;
  }

  String status(String? value) => code('status', value);
}

